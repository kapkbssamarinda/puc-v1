/**
 * Tingkat pengunduran diri per kelompok usia
 */
export const WITHDRAWAL_RATES = {
  // [minAge, maxAge]: rate per tahun
  ranges: [
    { min: 15, max: 29, rate: 0.060 },
    { min: 30, max: 34, rate: 0.030 },
    { min: 35, max: 39, rate: 0.018 },
    { min: 40, max: 53, rate: 0.012 },
    { min: 54, max: 55, rate: 0.006 },
    { min: 56, max: 99, rate: 0.000 },
  ],
};

export function getWithdrawalRate(age) {
  const r = WITHDRAWAL_RATES.ranges.find(r => age >= r.min && age <= r.max);
  return r ? r.rate : 0;
}

export function getMortalityRate(age) {
  const a = Math.min(Math.floor(age), 99);
  return TMI_IV_2019[a] ?? 0.05;
}

export function getDisabilityRate(age, disabilityFactor = 0.1) {
  return getMortalityRate(age) * disabilityFactor;
}
